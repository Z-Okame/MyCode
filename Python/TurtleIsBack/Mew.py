ROWS = 35
COLS = 35
SIZE = 19   # pixel turtle per cella (35*19=665, fits in 700)

ox = -(COLS * SIZE) / 2
oy =  (ROWS * SIZE) / 2

def draw_pixel(col, row, color):
    x = ox + col * SIZE
    y = oy - row * SIZE
    t.penup()
    t.goto(x, y)
    t.pendown()
    t.fillcolor(color)
    t.pencolor(color)
    t.pensize(1)
    t.begin_fill()
    for _ in range(4):
        t.forward(SIZE)
        t.left(90)
    t.end_fill()

for r, row in enumerate(grid):
    for c, color in enumerate(row):
        if color is not None:
            draw_pixel(c, r, color)

# Label
t.penup()
t.goto(0, -(ROWS * SIZE / 2) - 22)
t.pencolor("#222222")
